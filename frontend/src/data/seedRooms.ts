export function generateSeedRooms(): Room[] {
  return MUSHIA_EXCEL_ROOMS.map((item) => {
    const isReserved = Boolean(item.isReserved);

    // Standard baseline price per bed space
    let price = 6500;
    if (item.roomType === '4-in-1') price = item.airConditioned ? 7800 : 6500;
    else if (item.roomType === '3-in-1') price = item.airConditioned ? 9500 : 8200;
    else if (item.roomType === '2-in-1') price = item.airConditioned ? 12500 : 10800;
    else if (item.roomType === '1-in-1') price = item.airConditioned ? 16500 : 14000;

    if (item.size === 'Big') price += 400;

    const spaces: RoomSpace[] = [];

    for (let s = 1; s <= item.capacity; s++) {
      spaces.push({
        id: `${item.roomNumber}-space-${s}`,
        spaceNumber: s,
        status: isReserved ? 'paid' : 'available',
      });
    }

    const status: RoomStatus = isReserved ? 'fully_occupied' : 'available';

    return {
      id: `mushia-room-${item.roomNumber.toLowerCase()}`,
      roomNumber: item.roomNumber,
      floor: item.floor,
      floorIndex: item.floorIndex,
      roomType: item.roomType,
      capacity: item.capacity,
      size: item.size,
      airConditioned: item.airConditioned,
      price,
      status,
      spaces,
      images: [
        MUSHIA_IMAGES.interior,
        MUSHIA_IMAGES.exterior,
        MUSHIA_IMAGES.studyRoom,
        MUSHIA_IMAGES.lounge,
      ],
      features: [
        item.airConditioned ? 'Split-Unit Air Conditioning' : 'High-Velocity Ceiling Fan',
        'Built-in Wooden Wardrobe',
        'Study Desk & Ergonomic Chair',
        'En-suite Modern Washroom',
        '24/7 Water & Standby Generator Power',
        'High-Speed Wi-Fi Connectivity',
      ],
      description: `Comfortable ${item.roomType} ${item.airConditioned ? 'AC ' : ''}accommodation located on the ${item.floor} Floor of Mushia Hostel (Room ${item.roomNumber}). Features en-suite modern washroom, study desks, and 24/7 backup amenities.`,
    };
  });
}

